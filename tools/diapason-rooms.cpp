// Prints DP_ROOM_DECAY for src/diapason.cpp: each of Diapason's rooms' decay,
// measured by Cistern's engine exactly as a trace would measure it (from the
// space's own reference point, with the default BuildParams). Diapason ships
// the table so a room needs no decay measurement when it is first traced, which
// is most of the second or more a room took to come in. tools/diapason-harness.cpp
// fails if the table and the engine ever disagree: rerun this and paste.
//
//   clang++ -std=c++17 -O2 -I src tools/diapason-rooms.cpp -o /tmp/diapason-rooms && /tmp/diapason-rooms
//
// Run from the repository (it reads res/spaces).
#include "cistern-engine.hpp"
#include <cstdio>
#include <cstring>

int main() {
	const char* slugs[] = {"oldchurch", "bartless", "stourton", "hintze", "pantheon", "basilica"};
	printf("// generated by tools/diapason-rooms.cpp: t60 per band (125 Hz..4 kHz), t60 at 8 kHz, mean free path\n");
	printf("static const DpRoomDecay DP_ROOM_DECAY[DP_NROOM] = {\n");
	for (const char* sl : slugs) {
		int id = 0;
		for (int i = 0; i < cistern::NSPACES; i++) if (!std::strcmp(cistern::SPACES[i].slug, sl)) id = i;
		cistern::Space s; std::string err;
		if (!cistern::makeSpace(id, "res/spaces", s, err)) { fprintf(stderr, "%s: %s\n", sl, err.c_str()); return 1; }
		cistern::Program P;
		cistern::BuildParams bp;
		cistern::roomDecay(s, bp, s.src, P);
		printf("\t{{");
		for (int b = 0; b < cistern::NB; b++) printf("%s%.17g", b ? ", " : "", P.t60[b]);
		printf("}, %.17g, %.17g},   // %s\n", P.t60x8k, P.mfp, sl);
	}
	printf("};\n");
	return 0;
}
