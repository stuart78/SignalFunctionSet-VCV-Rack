// =============================================================================
// Diapason: a pipe organ in three divisions.
//
// Great, Swell and Pedal each have their own polyphonic V/OCT + GATE and their
// own stops, joined by three couplers. A coupler plays the same pipes rather
// than a second set, so the engine counts pipes (rank x key), not voices. Each
// division has its own wind, the Swell is enclosed in a box, and the outputs
// are placed across the case so Cistern's two sources can put the two halves
// of it in a church.
//
// The sound is src/diapason-engine.hpp, which runs without Rack and is measured
// and rendered by tools/diapason-proto.cpp. Design: docs/diapason-design.md.
// =============================================================================
