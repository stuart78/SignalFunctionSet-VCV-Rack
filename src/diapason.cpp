	void appendContextMenu(Menu* menu) override {
		Diapason* m = dynamic_cast<Diapason*>(module);
		if (!m) return;
		menu->addChild(new MenuSeparator);
		menu->addChild(createIndexSubmenuItem("Outputs with ROOM off",
			{"Left and right of the case", "C side and C# side (for Cistern's two sources)"},
			[=]() { return (size_t)(m->sidesOut ? 1 : 0); },
			[=](size_t i) { m->sidesOut = i == 1; }));
		menu->addChild(createIndexPtrSubmenuItem("Pipes",
			{"Steady (every pipe exact)", "Natural (each pipe voiced and winded a little differently)",
			 "Old organ (more of both)"}, &m->pipes));
		static const int SPL[5] = {0, 48, 53, 55, 60};
		menu->addChild(createIndexSubmenuItem("GREAT notes below a key play the Pedal",
			{"Off", "Below C3", "Below F3", "Below G3", "Below C4"},
			[=]() { for (int i = 0; i < 5; i++) if (m->split == SPL[i]) return (size_t)i; return (size_t)0; },
			[=](size_t i) { m->split = SPL[i]; }));
		menu->addChild(new MenuSeparator);
		menu->addChild(createMenuLabel("SET stores the stops drawn now in the current piston"));
		menu->addChild(createMenuItem("Restore the factory pistons", "", [=]() { m->loadFactory(); }));
		menu->addChild(createMenuLabel("Click a pipe on the case to play it"));
	}
