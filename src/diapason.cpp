static const NVGcolor DP_HOT = nvgRGB(0xEC, 0x65, 0x2E);

struct DiapasonDisplay : OpaqueWidget {
	Diapason* module = nullptr;
	struct PipeRect { int div, key; Rect r; };
	std::vector<PipeRect> rects;
	Rect boxRect[2];
	Vec lastSize;
	int pressDiv = -1;

	// one division's pipes: the C side from x0 (largest at the outside) and the
	// C# side mirrored from x1, standing on baseline y
	void layoutDiv(int div, float xa, float xb, bool outsideIn, float base, float hMax, float hMin) {
		int lo = diapason::Engine::compassLo(div), hi = diapason::Engine::compassHi(div);
		int nC = 0, nS = 0;
		for (int k = lo; k <= hi; k++) ((k - 36) & 1 ? nS : nC)++;
		int n = std::max(nC, nS);
		float halfW = (xb - xa) * 0.5f;
		float pitch = halfW / n, w = pitch * 0.78f;
		float ratio = hMin / hMax;
		for (int k = lo; k <= hi; k++) {
			int side = (k - 36) & 1;
			int idx = (k - lo) / 2;               // 0 the largest on its side
			float rel = (float)(k - lo) / (float)(hi - lo);
			float h = hMax * std::pow(ratio, rel);
			// outsideIn: the largest pipes at the outer ends, the smallest at the middle
			float off = outsideIn ? idx * pitch : (n - 1 - idx) * pitch;
			float x = side == 0 ? xa + off + (pitch - w) * 0.5f : xb - off - pitch + (pitch - w) * 0.5f;
			rects.push_back({div, k, Rect(Vec(x, base - h), Vec(w, h))});
		}
	}
	void layout() {
		rects.clear();
		float W = box.size.x, H = box.size.y;
		float base = H - mm2px(4.2f);
		float tw = mm2px(27.f), bw = mm2px(24.f), gap = mm2px(2.2f);
		// the pedal towers at the ends
		layoutDiv(PEDAL, 0.f, W, true, base, H - mm2px(6.f), mm2px(14.f));
		// squeeze the pedal into the two towers
		for (auto& p : rects) {
			float u = p.r.pos.x / W;
			float x = u < 0.5f ? u * 2.f * tw : W - tw + (u - 0.5f) * 2.f * tw;
			float s = 2.f * tw / W;
			p.r.pos.x = x; p.r.size.x *= s;
		}
		// the swell boxes, then the great between them
		float sx0 = tw + gap, sx1 = W - tw - gap;
		boxRect[0] = Rect(Vec(sx0, base - mm2px(27.f)), Vec(bw, mm2px(27.f)));
		boxRect[1] = Rect(Vec(sx1 - bw, base - mm2px(27.f)), Vec(bw, mm2px(27.f)));
		size_t i0 = rects.size();
		layoutDiv(SWELL, sx0, sx1, true, base - mm2px(1.f), mm2px(24.f), mm2px(4.f));
		for (size_t i = i0; i < rects.size(); i++) {
			PipeRect& p = rects[i];
			float u = (p.r.pos.x - sx0) / (sx1 - sx0);
			float x = u < 0.5f ? sx0 + mm2px(1.f) + u * 2.f * (bw - mm2px(2.f))
			                   : sx1 - bw + mm2px(1.f) + (u - 0.5f) * 2.f * (bw - mm2px(2.f));
			float s = (bw - mm2px(2.f)) / ((sx1 - sx0) * 0.5f);
			p.r.pos.x = x; p.r.size.x *= s;
		}
		float gx0 = sx0 + bw + gap, gx1 = sx1 - bw - gap;
		layoutDiv(GREAT, gx0, gx1, true, base, H - mm2px(9.f), mm2px(6.f));
		lastSize = box.size;
	}

	bool hit(Vec p, int& div, int& key) {
		for (int i = (int)rects.size() - 1; i >= 0; i--) {
			Rect r = rects[i].r;
			r.pos.x -= 1.f; r.size.x += 2.f;
			if (r.contains(p)) { div = rects[i].div; key = rects[i].key; return true; }
		}
		return false;
	}
	void onButton(const ButtonEvent& e) override {
		if (!module || e.button != GLFW_MOUSE_BUTTON_LEFT) { OpaqueWidget::onButton(e); return; }
		if (e.action == GLFW_PRESS) {
			int d, k;
			if (hit(e.pos, d, k)) { pressDiv = d; module->mouseKey[d] = k; e.consume(this); return; }
		}
		OpaqueWidget::onButton(e);
	}
	void onDragEnd(const DragEndEvent& e) override { release(); }
	void release() {
		if (module && pressDiv >= 0) module->mouseKey[pressDiv] = -1;
		pressDiv = -1;
	}
	void step() override {
		// a release outside the widget still lets the key go
		if (pressDiv >= 0 && APP->event->getDraggedWidget() != this) release();
		OpaqueWidget::step();
	}

	void drawPipe(NVGcontext* vg, Rect r, float lvl, const DpPal& P) {
		float foot = std::min(r.size.y * 0.22f, mm2px(4.f));
		float x = r.pos.x, y = r.pos.y, w = r.size.x, h = r.size.y - foot;
		NVGcolor fill = nvgLerpRGBA(P.pipe, DP_HOT, clamp(lvl, 0.f, 1.f));
		// the body
		nvgBeginPath(vg);
		nvgRect(vg, x, y, w, h);
		nvgFillColor(vg, fill); nvgFill(vg);
		// the foot, tapering to the toe
		nvgBeginPath(vg);
		nvgMoveTo(vg, x, y + h);
		nvgLineTo(vg, x + w, y + h);
		nvgLineTo(vg, x + w * 0.62f, y + h + foot);
		nvgLineTo(vg, x + w * 0.38f, y + h + foot);
		nvgClosePath(vg);
		nvgFill(vg);
		nvgStrokeColor(vg, P.pipeEdge); nvgStrokeWidth(vg, 0.5f);
		nvgBeginPath(vg);
		nvgRect(vg, x, y, w, h);
		nvgStroke(vg);
		// the mouth
		if (w > 2.f) {
			float my = y + h - std::min(w * 0.9f, h * 0.15f);
			nvgBeginPath(vg);
			nvgMoveTo(vg, x + w * 0.2f, y + h); nvgLineTo(vg, x + w * 0.2f, my);
			nvgLineTo(vg, x + w * 0.8f, my); nvgLineTo(vg, x + w * 0.8f, y + h);
			nvgStroke(vg);
		}
	}

	void draw(const DrawArgs& args) override {
		if (!module) { module = diapasonPreview(); draw(args); module = nullptr; return; }
		if (!lastSize.equals(box.size) || rects.empty()) layout();
		NVGcontext* vg = args.vg;
		DpPal P = dpPal();
		const diapason::Engine& E = module->eng;
		float base = box.size.y - mm2px(4.2f);

		// the impost every division stands on
		nvgBeginPath(vg);
		nvgRect(vg, 0.f, base, box.size.x, mm2px(1.1f));
		nvgFillColor(vg, P.impost); nvgFill(vg);

		// the swell boxes: their pipes, then the shutters over them
		for (const PipeRect& p : rects)
			if (p.div == SWELL) drawPipe(vg, p.r, E.keyLevel[SWELL][p.key], P);
		float open = module->curSwell;
		for (int b = 0; b < 2; b++) {
			Rect r = boxRect[b];
			const int NS = 9;
			float pitch = r.size.y / NS;
			float slat = pitch * (1.f - 0.82f * open);
			for (int s = 0; s < NS; s++) {
				nvgBeginPath(vg);
				nvgRect(vg, r.pos.x, r.pos.y + s * pitch + (pitch - slat) * 0.5f, r.size.x, slat);
				nvgFillColor(vg, nvgTransRGBAf(P.slat, 0.92f)); nvgFill(vg);
			}
			nvgBeginPath(vg);
			nvgRect(vg, r.pos.x, r.pos.y, r.size.x, r.size.y);
			nvgStrokeColor(vg, P.box); nvgStrokeWidth(vg, 0.9f); nvgStroke(vg);
		}
		for (const PipeRect& p : rects)
			if (p.div != SWELL) drawPipe(vg, p.r, E.keyLevel[p.div][p.key], P);

		// the division names and their wind
		std::shared_ptr<Font> font = sfs::panelFont();
		if (!font || font->handle < 0) return;
		nvgFontFaceId(vg, font->handle);
		nvgTextLetterSpacing(vg, 0.f);
		nvgFontSize(vg, mm2px(sfs::NVG_EM * sfs::TYPE_NOTE));
		nvgFillColor(vg, P.soft);
		nvgTextAlign(vg, NVG_ALIGN_CENTER | NVG_ALIGN_BASELINE);
		float ty = box.size.y - mm2px(0.6f);
		float W = box.size.x, tw = mm2px(27.f), gap = mm2px(2.2f), bw = mm2px(24.f);
		auto wind = [&](int d) { return string::f("%s  WIND %.0f%%", DIV_NAME[d], 100.f * E.pressure[d]); };
		nvgText(vg, tw * 0.5f, ty, wind(PEDAL).c_str(), NULL);
		std::string rn = module->roomNow > 0 ? dpRoomName(module->roomNow - 1) : std::string("DRY");
		for (char& c : rn) c = (char)std::toupper((unsigned char)c);
		nvgText(vg, W - tw * 0.5f, ty, rn.c_str(), NULL);
		nvgText(vg, tw + gap + bw * 0.5f, ty, wind(SWELL).c_str(), NULL);
		nvgText(vg, W - tw - gap - bw * 0.5f, ty, string::f("BOX %.0f%% OPEN", 100.f * open).c_str(), NULL);
		nvgText(vg, W * 0.5f, ty, wind(GREAT).c_str(), NULL);
	}
};

